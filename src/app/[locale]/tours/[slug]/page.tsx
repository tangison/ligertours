import { pageMeta } from "@/lib/seo";

type Params = { params: Promise<{ locale: string; slug: string }> };

const siteUrl = process.env.NEXT_PUBLIC_SITE_URL || "https://ligertours.com";

export function generateStaticParams() {
  /* Locale segment is generated by the parent [locale] layout. */
  const dict = getDict("en");
  return dict.tours.map((t) => ({ slug: t.slug }));
}

export async function generateMetadata({ params }: Params): Promise<Metadata> {
  const { locale, slug } = await params;
  const dict = getDict(locale as Locale);
  const tour = dict.tours.find((t) => t.slug === slug);
  if (!tour) return {};
  const meta = pageMeta(locale as Locale, `/tours/${slug}`, {
    title: tour.metaTitle,
    description: tour.blurb.slice(0, 155),
  });
  return {
    ...meta,
    openGraph: {
      ...meta.openGraph,
      images: [
        {
          url: tour.image.replace("-4x5", "-16x9"),
          width: 1600,
          height: 900,
          alt: tour.alt,
        },
      ],
    },
  };
}

